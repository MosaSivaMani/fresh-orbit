// Copies the illustration files into the Flutter app and writes a Dart slot map.
//   pnpm --filter @fresh/illustrations sync-mobile
//   pnpm --filter @fresh/illustrations sync-mobile -- --dart <path from repo root>
//
// Writes
//   apps/mobile/assets/illustrations/<files>                         (declare the folder in pubspec.yaml)
//   apps/mobile/lib/core/illustrations/illustration_slots.g.dart     (default; Dart can import only from lib/)
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { baseName } from "../src/manifest.ts";
import { packageRoot, readManifest, repoRoot } from "./lib.ts";

const ASSET_DIR = "apps/mobile/assets/illustrations";
const dartFlag = process.argv.indexOf("--dart");
const dartPath =
  dartFlag >= 0 && process.argv[dartFlag + 1]
    ? process.argv[dartFlag + 1]!
    : "apps/mobile/lib/core/illustrations/illustration_slots.g.dart";

const manifest = readManifest();
const assetsOut = join(repoRoot, ASSET_DIR);
mkdirSync(assetsOut, { recursive: true });

const files = new Set<string>();
for (const entry of manifest.slots) {
  files.add(entry.placeholder);
  files.add(entry.file);
}
for (const file of files) copyFileSync(join(packageRoot, file), join(assetsOut, baseName(file)));

const camel = (slot: string): string =>
  slot.toLowerCase().replace(/_([a-z0-9])/g, (_m, c: string) => c.toUpperCase());
const dartString = (s: string): string => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

const dart = `// Generated by @fresh/illustrations (scripts/sync-mobile.ts) from manifest.json. Do not edit by hand.
// ignore_for_file: public_member_api_docs

/// Every illustration slot (D53). Same codes as the web manifest.
enum IllustrationSlot {
${manifest.slots.map((s) => `  ${camel(s.slot)}('${s.slot}'),`).join("\n")};

  const IllustrationSlot(this.code);

  /// The UPPER_SNAKE slot code used in manifest.json.
  final String code;
}

/// One slot's image: the final WebP when [isFinal], else our placeholder SVG.
class IllustrationAsset {
  const IllustrationAsset({
    required this.asset,
    required this.placeholder,
    required this.alt,
    required this.aspectRatio,
    required this.transparent,
    required this.isFinal,
  });

  /// Asset path to show (WebP when FINAL, otherwise the SVG placeholder).
  final String asset;

  /// Placeholder SVG asset path (always present).
  final String placeholder;

  /// One plain sentence for screen readers (Semantics label).
  final String alt;

  /// Width divided by height (1.0 or 4/3).
  final double aspectRatio;

  /// True when the image has no background of its own.
  final bool transparent;

  final bool isFinal;
}

const Map<IllustrationSlot, IllustrationAsset> illustrationAssets = <IllustrationSlot, IllustrationAsset>{
${manifest.slots
  .map((s) => {
    const final = s.status === "FINAL";
    const asset = `assets/illustrations/${baseName(final ? s.file : s.placeholder)}`;
    return `  IllustrationSlot.${camel(s.slot)}: IllustrationAsset(
    asset: ${dartString(asset)},
    placeholder: ${dartString(`assets/illustrations/${baseName(s.placeholder)}`)},
    alt: ${dartString(s.alt)},
    aspectRatio: ${s.aspect === "1:1" ? "1.0" : "4 / 3"},
    transparent: ${s.background === "TRANSPARENT"},
    isFinal: ${final},
  ),`;
  })
  .join("\n")}
};
`;

const dartOut = join(repoRoot, dartPath);
mkdirSync(dirname(dartOut), { recursive: true });
writeFileSync(dartOut, dart);
console.log(`illustrations: copied ${files.size} files to ${ASSET_DIR} and wrote ${dartPath}.`);
