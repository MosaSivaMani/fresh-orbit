// Writes the runtime module the apps import (no prompts, only what a page needs).
//   dist/index.js + dist/index.d.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { checkManifest, toRuntime } from "../src/manifest.ts";
import { diskFacts, packageRoot, readManifest } from "./lib.ts";

const manifest = readManifest();
const problems = checkManifest(manifest, diskFacts);
if (problems.length > 0) {
  console.error(
    "illustrations: manifest is invalid; run `pnpm --filter @fresh/illustrations validate`.",
  );
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

const HEADER = "Generated by @fresh/illustrations from manifest.json. Do not edit by hand.";
const entries = Object.fromEntries(manifest.slots.map((s) => [s.slot, toRuntime(s)]));
const slots = manifest.slots.map((s) => s.slot);
const json = JSON.stringify(entries, null, 2);

const js = `// ${HEADER}
/** Every illustration slot, keyed by slot code. */
export const illustrations = Object.freeze(${json});

/** Slot codes in manifest order. */
export const illustrationSlots = Object.freeze(${JSON.stringify(slots)});
`;

const dts = `// ${HEADER}
export type IllustrationSlot =
${slots.map((s) => `  | "${s}"`).join("\n")};

export type IllustrationAspect = "1:1" | "4:3" | "2:1";
/** SAND: sand backdrop. TRANSPARENT: cut-out subject. SCENE: full picture with its own scenery (show it cropped with cover). */
export type IllustrationBackground = "TRANSPARENT" | "SAND" | "SCENE";
export type IllustrationStatus = "PLACEHOLDER" | "FINAL";

export interface IllustrationEntry {
  slot: IllustrationSlot;
  /** File name relative to the folder the assets are served from (the final JPEG, PNG or WebP when FINAL, else the SVG). */
  src: string;
  /** One plain sentence for screen readers. */
  alt: string;
  aspect: IllustrationAspect;
  background: IllustrationBackground;
  status: IllustrationStatus;
  /** Intrinsic size in pixels: the final file's size when FINAL, else the design size (1024 wide). */
  width: number;
  height: number;
}

export declare const illustrations: Readonly<Record<IllustrationSlot, IllustrationEntry>>;
export declare const illustrationSlots: readonly IllustrationSlot[];
`;

const dist = join(packageRoot, "dist");
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, "index.js"), js);
writeFileSync(join(dist, "index.d.ts"), dts);
console.log(`illustrations: wrote dist/index.js and dist/index.d.ts (${slots.length} slots).`);
