// Generates every token output from tokens.json. Plain Node (type stripping), no dependencies.
//
//   dist/tokens.css          CSS custom properties (--fo-*), light on :root, dark on [data-theme="dark"] / .dark
//   dist/tailwind-theme.css  Tailwind v4 @theme mapping utilities to the CSS variables
//   dist/index.js + .d.ts    `tokens` object (literal types), `tailwindTheme`, `cssVar()`
//   dist/tokens.json         copy of the source
//   ../flutter/fresh_theme/lib/src/tokens.g.dart   Dart constants + FreshColors ThemeExtension
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const dartOut = join(root, "..", "flutter", "fresh_theme", "lib", "src", "tokens.g.dart");

type TypeSize = { size: number; lineHeight: number };
interface Tokens {
  brand: Record<string, string>;
  color: { light: Record<string, string>; dark: Record<string, string> };
  font: { sans: string; display: string; mono: string; weight: Record<string, number> };
  typeScale: Record<string, TypeSize>;
  spacing: Record<string, number | string>;
  radius: Record<string, number>;
  /** A string is shared by both themes; an object sets each theme. */
  shadow: Record<string, string | { light: string; dark: string }>;
  motion: { duration: Record<string, number>; easing: Record<string, string> };
  breakpoint: Record<string, number>;
  zIndex: Record<string, number>;
}

const source = readFileSync(join(root, "tokens.json"), "utf8");
const tokens = JSON.parse(source) as Tokens;

const HEADER = "Generated by @fresh/design-tokens from tokens.json. Do not edit by hand.";

const kebab = (s: string): string =>
  s
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/\./g, "_")
    .toLowerCase();
const rem = (px: number): string => (px === 0 ? "0" : `${px / 16}rem`);
const entries = <T>(o: Record<string, T>): [string, T][] =>
  Object.entries(o).filter(([k]) => !k.startsWith("$"));

// ---------- CSS variables ----------
function colorVars(palette: Record<string, string>, indent = "  "): string {
  return entries(palette)
    .map(([k, v]) => `${indent}--fo-color-${kebab(k)}: ${v};`)
    .join("\n");
}

function darkShadow(value: string): string {
  return value.replace(/rgb\(7 59 76 \/ ([0-9.]+)\)/g, (_m, a: string) => {
    const alpha = Math.min(0.6, Number(a) * 3);
    return `rgb(0 0 0 / ${Number(alpha.toFixed(2))})`;
  });
}

function buildCss(): string {
  const shared: string[] = [];
  for (const [k, v] of entries(tokens.brand)) shared.push(`  --fo-brand-${kebab(k)}: ${v};`);
  shared.push(`  --fo-font-sans: ${tokens.font.sans};`);
  shared.push(`  --fo-font-display: ${tokens.font.display};`);
  shared.push(`  --fo-font-mono: ${tokens.font.mono};`);
  for (const [k, v] of entries(tokens.font.weight)) shared.push(`  --fo-font-weight-${k}: ${v};`);
  for (const [k, v] of entries(tokens.typeScale)) {
    shared.push(`  --fo-text-${k}: ${rem(v.size)};`);
    shared.push(`  --fo-text-${k}-line-height: ${rem(v.lineHeight)};`);
  }
  for (const [k, v] of entries(tokens.spacing))
    shared.push(`  --fo-space-${kebab(k)}: ${rem(Number(v))};`);
  for (const [k, v] of entries(tokens.radius))
    shared.push(`  --fo-radius-${k}: ${k === "full" ? "9999px" : rem(v)};`);
  for (const [k, v] of entries(tokens.motion.duration))
    shared.push(`  --fo-duration-${k}: ${v}ms;`);
  for (const [k, v] of entries(tokens.motion.easing)) shared.push(`  --fo-ease-${k}: ${v};`);
  for (const [k, v] of entries(tokens.zIndex)) shared.push(`  --fo-z-${kebab(k)}: ${v};`);

  const lightShadows = entries(tokens.shadow).map(
    ([k, v]) => `  --fo-shadow-${k}: ${typeof v === "string" ? v : v.light};`,
  );
  const darkShadows = entries(tokens.shadow).map(
    ([k, v]) => `  --fo-shadow-${k}: ${typeof v === "string" ? darkShadow(v) : v.dark};`,
  );

  return `/* ${HEADER} */
:root,
[data-theme="light"] {
${shared.join("\n")}
${colorVars(tokens.color.light)}
${lightShadows.join("\n")}
}

[data-theme="dark"],
.dark {
${colorVars(tokens.color.dark)}
${darkShadows.join("\n")}
}
`;
}

// ---------- Tailwind v4 theme ----------
function buildTailwindCss(): string {
  const lines: string[] = [];
  for (const k of Object.keys(tokens.color.light))
    lines.push(`  --color-${kebab(k)}: var(--fo-color-${kebab(k)});`);
  for (const k of Object.keys(tokens.brand))
    lines.push(`  --color-brand-${kebab(k)}: var(--fo-brand-${kebab(k)});`);
  lines.push("  --font-sans: var(--fo-font-sans);");
  lines.push("  --font-display: var(--fo-font-display);");
  lines.push("  --font-mono: var(--fo-font-mono);");
  for (const k of Object.keys(tokens.typeScale)) {
    lines.push(`  --text-${k}: var(--fo-text-${k});`);
    lines.push(`  --text-${k}--line-height: var(--fo-text-${k}-line-height);`);
  }
  for (const k of Object.keys(tokens.radius)) lines.push(`  --radius-${k}: var(--fo-radius-${k});`);
  for (const [k] of entries(tokens.shadow)) lines.push(`  --shadow-${k}: var(--fo-shadow-${k});`);
  for (const k of Object.keys(tokens.motion.easing))
    lines.push(`  --ease-${k}: var(--fo-ease-${k});`);

  const breakpoints = entries(tokens.breakpoint).map(([k, v]) => `  --breakpoint-${k}: ${rem(v)};`);

  return `/* ${HEADER} */
/* Only token colours exist; Tailwind's default palette is removed. */
@theme {
  --color-*: initial;
  --color-white: #ffffff;
  --color-black: #000000;
  --spacing: 0.25rem;
${breakpoints.join("\n")}
}

@theme inline {
${lines.join("\n")}
}
`;
}

// ---------- JS / TS ----------
function tailwindThemeObject(): Record<string, unknown> {
  const colors: Record<string, string> = {};
  for (const k of Object.keys(tokens.color.light)) colors[kebab(k)] = `var(--fo-color-${kebab(k)})`;
  for (const k of Object.keys(tokens.brand))
    colors[`brand-${kebab(k)}`] = `var(--fo-brand-${kebab(k)})`;
  const fontSize: Record<string, [string, { lineHeight: string }]> = {};
  for (const k of Object.keys(tokens.typeScale))
    fontSize[k] = [`var(--fo-text-${k})`, { lineHeight: `var(--fo-text-${k}-line-height)` }];
  const map = (o: Record<string, unknown>, prefix: string) =>
    Object.fromEntries(
      Object.keys(o)
        .filter((k) => !k.startsWith("$"))
        .map((k) => [k, `var(--fo-${prefix}-${k})`]),
    );
  return {
    colors,
    fontFamily: {
      sans: "var(--fo-font-sans)",
      display: "var(--fo-font-display)",
      mono: "var(--fo-font-mono)",
    },
    fontSize,
    borderRadius: map(tokens.radius, "radius"),
    boxShadow: map(tokens.shadow, "shadow"),
    transitionDuration: map(tokens.motion.duration, "duration"),
    transitionTimingFunction: map(tokens.motion.easing, "ease"),
  };
}

function buildJs(): { js: string; dts: string } {
  const clean = JSON.parse(source, (k, v: unknown) =>
    k.startsWith("$") ? undefined : v,
  ) as object;
  const tw = tailwindThemeObject();
  const json = JSON.stringify(clean, null, 2);
  const twJson = JSON.stringify(tw, null, 2);
  const js = `// ${HEADER}
export const tokens = Object.freeze(${json});

/** Tailwind theme (v3-style object) whose values are the CSS variables from tokens.css. */
export const tailwindTheme = Object.freeze(${twJson});

/** Reference a token CSS variable, e.g. cssVar("color", "primary") -> "var(--fo-color-primary)". */
export function cssVar(group, name) {
  const kebab = String(name).replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/\\./g, "_").toLowerCase();
  return \`var(--fo-\${group}-\${kebab})\`;
}
`;
  const dts = `// ${HEADER}
export declare const tokens: ${json.replace(/\n/g, "\n")};
export type Tokens = typeof tokens;
export type ColorRole = keyof Tokens["color"]["light"];
export type ThemeName = keyof Tokens["color"];
export declare const tailwindTheme: ${twJson};
export declare function cssVar(
  group: "color" | "brand" | "font" | "text" | "space" | "radius" | "shadow" | "duration" | "ease" | "z",
  name: string,
): string;
`;
  return { js, dts };
}

// ---------- Dart ----------
const dartColor = (hex: string): string => `Color(0xFF${hex.replace("#", "").toUpperCase()})`;
const dartIdent = (k: string): string => {
  const s = k.replace(/\./g, "_");
  return /^[0-9]/.test(s) ? `s${s}` : s;
};

function buildDart(): string {
  const roles = Object.keys(tokens.color.light);
  const fields = roles.map((r) => `  final Color ${r};`).join("\n");
  const ctorParams = roles.map((r) => `    required this.${r},`).join("\n");
  const instance = (name: "light" | "dark") =>
    `  static const FreshColors ${name} = FreshColors(\n${roles
      .map((r) => `    ${r}: ${dartColor(tokens.color[name][r] as string)},`)
      .join("\n")}\n  );`;
  const copyWithParams = roles.map((r) => `    Color? ${r},`).join("\n");
  const copyWithBody = roles.map((r) => `      ${r}: ${r} ?? this.${r},`).join("\n");
  const lerpBody = roles.map((r) => `      ${r}: Color.lerp(${r}, other.${r}, t)!,`).join("\n");

  const typeNames: Record<string, string> = {
    "2xl": "xl2",
    "3xl": "xl3",
    "4xl": "xl4",
    "5xl": "xl5",
  };
  const typeScale = entries(tokens.typeScale)
    .map(
      ([k, v]) =>
        `  static const FreshTypeSize ${typeNames[k] ?? k} = FreshTypeSize(${v.size}, ${v.lineHeight});`,
    )
    .join("\n");
  const spacing = entries(tokens.spacing)
    .map(([k, v]) => `  static const double ${dartIdent(k)} = ${Number(v).toFixed(1)};`)
    .join("\n");
  const radius = entries(tokens.radius)
    .map(([k, v]) => `  static const double ${typeNames[k] ?? k} = ${Number(v).toFixed(1)};`)
    .join("\n");
  const durations = entries(tokens.motion.duration)
    .map(([k, v]) => `  static const Duration ${k} = Duration(milliseconds: ${v});`)
    .join("\n");
  const brand = entries(tokens.brand)
    .map(([k, v]) => `  static const Color ${k} = ${dartColor(v)};`)
    .join("\n");
  const weights = entries(tokens.font.weight)
    .map(([k, v]) => `  static const FontWeight ${k} = FontWeight.w${v};`)
    .join("\n");
  const firstFamily = (stack: string) => stack.split(",")[0]!.trim().replace(/"/g, "");
  const fallback = (stack: string) =>
    stack
      .split(",")
      .slice(1)
      .map((s) => s.trim().replace(/"/g, ""))
      .filter((s) => !/^(ui-|system-ui|-apple-system|sans-serif|monospace)/.test(s))
      .map((s) => `'${s}'`)
      .join(", ");
  const breakpoints = entries(tokens.breakpoint)
    .map(([k, v]) => `  static const double ${typeNames[k] ?? k} = ${v.toFixed(1)};`)
    .join("\n");

  return `// ${HEADER}
// ignore_for_file: public_member_api_docs

part of '../fresh_theme.dart';

/// The four brand colours, exactly as specified.
abstract final class FreshBrand {
${brand}
}

/// Semantic colour roles for one theme. Registered as a [ThemeExtension] by [FreshTheme].
@immutable
class FreshColors extends ThemeExtension<FreshColors> {
  const FreshColors({
${ctorParams}
  });

${fields}

${instance("light")}

${instance("dark")}

  @override
  FreshColors copyWith({
${copyWithParams}
  }) {
    return FreshColors(
${copyWithBody}
    );
  }

  @override
  FreshColors lerp(covariant ThemeExtension<FreshColors>? other, double t) {
    if (other is! FreshColors) {
      return this;
    }
    return FreshColors(
${lerpBody}
    );
  }
}

/// A font size with its line height, both in logical pixels.
@immutable
class FreshTypeSize {
  const FreshTypeSize(this.size, this.lineHeight);

  final double size;
  final double lineHeight;

  /// Line height as a multiple of the font size, for [TextStyle.height].
  double get height => lineHeight / size;
}

abstract final class FreshTypeScale {
${typeScale}
}

abstract final class FreshFonts {
  static const String sans = '${firstFamily(tokens.font.sans)}';
  static const List<String> sansFallback = <String>[${fallback(tokens.font.sans)}];
  static const String display = '${firstFamily(tokens.font.display)}';
  static const List<String> displayFallback = <String>[${fallback(tokens.font.display)}];
  static const String mono = '${firstFamily(tokens.font.mono)}';
}

abstract final class FreshFontWeights {
${weights}
}

/// Spacing in logical pixels; \`s4\` = 16.
abstract final class FreshSpacing {
${spacing}
}

/// Corner radii in logical pixels.
abstract final class FreshRadius {
${radius}
}

abstract final class FreshDurations {
${durations}
}

/// Layout breakpoints in logical pixels.
abstract final class FreshBreakpoints {
${breakpoints}
}
`;
}

mkdirSync(dist, { recursive: true });
mkdirSync(dirname(dartOut), { recursive: true });
writeFileSync(join(dist, "tokens.css"), buildCss());
writeFileSync(join(dist, "tailwind-theme.css"), buildTailwindCss());
const { js, dts } = buildJs();
writeFileSync(join(dist, "index.js"), js);
writeFileSync(join(dist, "index.d.ts"), dts);
writeFileSync(join(dist, "tokens.json"), source);
writeFileSync(dartOut, buildDart());
console.log(
  "design-tokens: wrote dist/tokens.css, dist/tailwind-theme.css, dist/index.js, dist/index.d.ts, tokens.g.dart",
);
